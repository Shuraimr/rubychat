// Generates src/lib/emoji/veri-ham.ts: every fully-qualified emoji (Unicode emoji-test.txt) with Turkish + English search words (CLDR).
// Usage: node scripts/emoji-uret.mjs <emoji-test.txt> <cldr/common dir>. Data: © Unicode, Inc. (public/lisanslar/unicode.txt).
// src/lib/emoji/veri-ham.ts dosyasını üretir: tam nitelikli her emoji (Unicode emoji-test.txt) ve Türkçe + İngilizce arama kelimeleri (CLDR).
// Kullanım: node scripts/emoji-uret.mjs <emoji-test.txt> <cldr/common klasörü>. Veri: © Unicode, Inc. (public/lisanslar/unicode.txt).
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const [, , testYolu, cldr] = process.argv;
const HEDEF = new URL("../src/lib/emoji/veri-ham.ts", import.meta.url);
const EL_YAZISI = new URL("./emoji-el-yazisi.txt", import.meta.url);
const yalin = (s) => s.replaceAll("️", "");
const kacis = (s) => s.replaceAll("&lt;", "<").replaceAll("&gt;", ">").replaceAll("&quot;", '"').replaceAll("&amp;", "&");

function anlam(dil) {
  const m = new Map();
  for (const tur of ["annotations", "annotationsDerived"]) {
    for (const [, cp, , deger] of readFileSync(`${cldr}/${tur}/${dil}.xml`, "utf8").matchAll(/<annotation cp="([^"]+)"( type="tts")?>([^<]*)</g)) {
      m.set(kacis(cp), `${m.get(kacis(cp)) ?? ""} ${kacis(deger).replace(/[|:]/g, " ")}`);
    }
  }
  return m;
}
const katla = (s) => s.toLocaleLowerCase("tr").replace(/[ışçğöüâîû]/g, (h) => "iscgouaiu"["ışçğöüâîû".indexOf(h)]);
const kelimeler = (...s) => [...new Set(katla(s.join(" ")).split(/[\s|,()“”"`\\]+/).filter((k) => k.length > 1 || /\d/.test(k)))].join(" ");

const tr = anlam("tr");
const en = anlam("en");
// The hand-written keywords of the first, curated set stay. · İlk, küratörlü kümenin elle yazılmış kelimeleri kalır.
const el = new Map(existsSync(EL_YAZISI) ? readFileSync(EL_YAZISI, "utf8").trim().split("\n").map((l) => { const [e, ...k] = l.split("|"); return [yalin(e.trim()), k.join(" ")]; }) : []);

const TON = /[\u{1F3FB}-\u{1F3FF}]/u;
const TONLAR = /[\u{1F3FB}-\u{1F3FF}]/gu;
const gruplar = { yuzler: [], eller: [], kalpler: [], hayvanlar: [], yiyecek: [], etkinlik: [], seyahat: [], nesneler: [], semboller: [], bayraklar: [] };
const BAS = { "Smileys & Emotion": "yuzler", "People & Body": "eller", "Animals & Nature": "hayvanlar", "Food & Drink": "yiyecek", "Travel & Places": "seyahat", Activities: "etkinlik", Objects: "nesneler", Symbols: "semboller", Flags: "bayraklar" };
let grup = "", alt = "";
const hepsi = [];
const tonlu = new Set();
for (const l of readFileSync(testYolu, "utf8").split("\n")) {
  if (l.startsWith("# group: ")) grup = BAS[l.slice(9)];
  else if (l.startsWith("# subgroup: ")) alt = l.slice(12);
  const m = /^[0-9A-F ]+; fully-qualified\s+# (\S+) E[\d.]+ (.*)$/.exec(l);
  if (!m || !grup) continue;
  if (TON.test(m[1])) { tonlu.add(m[1]); continue; }
  // "facing right" doubles only clutter the list. · "sağa bakan" kopyalar listeyi kalabalıklaştırır.
  if (/facing right/.test(m[2])) continue;
  hepsi.push({ e: m[1], ad: m[2], g: grup === "yuzler" && ["heart", "emotion"].includes(alt) ? "kalpler" : grup });
}
// Must match `tenli` in veri.ts. Emoji that take one tone after their first character get a leading "*".
// veri.ts'teki `tenli` ile aynı olmalı. İlk karakterinden sonra tek ton alan emojiler başa "*" alır.
const tenli = (e, ton) => { const [bas, ...kalan] = [...e]; return bas + ton + (kalan[0] === "️" ? kalan.slice(1) : kalan).join(""); };
const TUMTON = ["🏻", "🏼", "🏽", "🏾", "🏿"];
let n = 0;
for (const { e, ad, g } of hepsi) {
  const y = yalin(e);
  const yildiz = TUMTON.every((ton) => tonlu.has(tenli(e, ton))) ? "*" : "";
  gruplar[g].push(`${yildiz}${e}|${kelimeler(el.get(y) ?? "", tr.get(y) ?? "", en.get(y) ?? "", ad)}`);
  n++;
}
writeFileSync(HEDEF, `// GENERATED by scripts/emoji-uret.mjs, do not edit. Data © Unicode, Inc. (emoji-test.txt + CLDR, see public/lisanslar/unicode.txt).
// scripts/emoji-uret.mjs ÜRETTİ, elle değiştirme. Veri © Unicode, Inc. (emoji-test.txt + CLDR, bkz. public/lisanslar/unicode.txt).
// "emoji|search words" per line; a leading "*" = takes a skin tone · satır başına "emoji|arama kelimeleri"; baştaki "*" = ten rengi alır
export const HAM = {
${Object.entries(gruplar).map(([id, s]) => `  ${id}: \`\n${s.join("\n")}\n\`,`).join("\n")}
} as const;
`);
console.log(n, Object.fromEntries(Object.entries(gruplar).map(([k, v]) => [k, v.length])), [...gruplar.eller].filter((x) => x.startsWith("*")).length);
